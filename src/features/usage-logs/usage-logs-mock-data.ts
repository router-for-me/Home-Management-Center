function sum(values: number[]) {
  return values.reduce((total, value) => total + value, 0)
}

function weightedAverage(
  items: UsageAnalyticsTimeBucket[],
  valueKey: 'avgDurationMs' | 'avgFirstTokenMs',
) {
  const requests = sum(items.map((item) => item.requests))
  if (requests === 0) return 0

  return Math.round(sum(items.map((item) => item[valueKey] * item.requests)) / requests)
}

function createSnapshot(seed: UsageAnalyticsMockSeed): UsageAnalyticsSnapshot {
  const requests = sum(seed.timeseries.map((item) => item.requests))
  const success = sum(seed.timeseries.map((item) => item.success))
  const failed = sum(seed.timeseries.map((item) => item.failed))

  return {
    ...seed,
    generatedAt: '2026-05-26T14:00:00.000Z',
    summary: {
      requests,
      success,
      failed,
      failureRate: requests > 0 ? Number(((failed / requests) * 100).toFixed(1)) : 0,
      totalTokens: sum(seed.timeseries.map((item) => item.totalTokens)),
      inputTokens: sum(seed.timeseries.map((item) => item.inputTokens)),
      outputTokens: sum(seed.timeseries.map((item) => item.outputTokens)),
      cacheReadTokens: sum(seed.timeseries.map((item) => item.cacheReadTokens)),
      cacheWriteTokens: sum(seed.timeseries.map((item) => item.cacheWriteTokens)),
      cost: Number(sum(seed.timeseries.map((item) => item.cost)).toFixed(2)),
      avgDurationMs: weightedAverage(seed.timeseries, 'avgDurationMs'),
      avgFirstTokenMs: weightedAverage(seed.timeseries, 'avgFirstTokenMs'),
      activeClientKeys: seed.breakdowns.clientKeys.length,
      activeModels: seed.breakdowns.models.length,
      unpricedRequests: seed.scenarioId === 'empty' ? 0 : seed.scenarioId === 'spiky' ? 31 : 7,
    },
  }
}

